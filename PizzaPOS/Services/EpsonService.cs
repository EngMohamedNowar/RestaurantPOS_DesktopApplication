        // ── Resolve Printer for RAW sending ─────────
        // ── LocalPrintServer أول، fallback لـ list ──
        // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
        static string ResolvePrinterName(string name)
        {
            // لو في اسم محدد في الـ settings استخدمه مباشرة
            if (!string.IsNullOrWhiteSpace(name)) return name;

            try
            {
                using var server = new LocalPrintServer();
                var queues = server.GetPrintQueues();

                var found = queues.FirstOrDefault(q =>
                    q.Name.IndexOf("TM-T88V", StringComparison.OrdinalIgnoreCase) >= 0)
                  ?? queues.FirstOrDefault(q =>
                    q.Name.IndexOf("TM-T88", StringComparison.OrdinalIgnoreCase) >= 0)
                  ?? queues.FirstOrDefault(q =>
                    q.Name.IndexOf("Epson", StringComparison.OrdinalIgnoreCase) >= 0)
                  ?? queues.FirstOrDefault(q =>
                    q.Name.IndexOf("POS", StringComparison.OrdinalIgnoreCase) >= 0)
                  ?? queues.FirstOrDefault(q =>
                    q.Name.IndexOf("Receipt", StringComparison.OrdinalIgnoreCase) >= 0);

                if (found != null) return found.Name;
            }
            catch { /* سقط على fallback */ }

            // fallback: PrinterSettings.InstalledPrinters
            var all = PrinterSettings.InstalledPrinters.Cast<string>().ToList();
            return all.FirstOrDefault(p =>
                       p.Contains("TM-T88V", StringComparison.OrdinalIgnoreCase))
                ?? all.FirstOrDefault(p =>
                       p.Contains("TM-T88", StringComparison.OrdinalIgnoreCase))
                ?? all.FirstOrDefault(p =>
                       p.Contains("Epson", StringComparison.OrdinalIgnoreCase))
                ?? all.FirstOrDefault(p =>
                       p.Contains("POS", StringComparison.OrdinalIgnoreCase))
                ?? all.FirstOrDefault(p =>
                       p.Contains("Receipt", StringComparison.OrdinalIgnoreCase))
                ?? throw new InvalidOperationException(
                    "No thermal printer found.\nConnect the printer and set its name in Settings.");
        }

