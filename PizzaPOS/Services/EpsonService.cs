        static bool ShouldOpenDrawer(string modes, string pay)
        {
            string payEn = Tr(pay);
            return !string.IsNullOrWhiteSpace(modes) &&
                   modes.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries)
                        .Any(m => m.Equals(pay, StringComparison.OrdinalIgnoreCase) ||
                                  m.Equals(payEn, StringComparison.OrdinalIgnoreCase));
        }

