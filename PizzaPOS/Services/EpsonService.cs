            int.TryParse(db.GetSetting("SerialBaud", "115200"), out int b) && b > 0 ? b : 115200;

        static string TruncateLine(string s, int max) => s.Length > max ? s[..max] : s;

        static IEnumerable<string> WrapText(string text, int width)
        {
            if (string.IsNullOrEmpty(text)) yield break;
            int start = 0;
            while (start < text.Length)
            {
                int len = Math.Min(width, text.Length - start);
                if (start + len < text.Length)
                {
                    int ls = text.LastIndexOf(' ', start + len - 1, len);
                    if (ls > start) len = ls - start;
                }
                yield return text.Substring(start, len).TrimEnd();
                start += len;
                if (start < text.Length && text[start] == ' ') start++;
            }
        }

        static byte[] Combine(params byte[][] arrays)
        {
            using var ms = new MemoryStream();
            foreach (var a in arrays) ms.Write(a);
            return ms.ToArray();
        }

        static void SendSerial(string port, int baud, byte[] data)
        {
            var sp = new SerialPort(port)
            {
                BaudRate = baud,
                DataBits = 8,
                Parity = Parity.None,
                StopBits = StopBits.One,
                WriteTimeout = 5000,
                ReadTimeout = 2000
            };
            try
            {
                sp.Open();
                sp.Write(data, 0, data.Length);
                sp.BaseStream.Flush();
                System.Threading.Thread.Sleep(80);
            }
            finally { if (sp.IsOpen) sp.Close(); sp.Dispose(); }
        }

        static void SendRaw(string printerName, byte[] data)
        {
            if (!OpenPrinter(printerName.Trim(), out nint h, nint.Zero))
                throw new InvalidOperationException(
                    $"Cannot open printer: {printerName}\nCode: {Marshal.GetLastWin32Error()}");

            var di = new DocInfo { pDocName = "PizzaPOS-Receipt", pDataType = "RAW" };
            try
            {
                if (!StartDocPrinter(h, 1, ref di))
                    throw new InvalidOperationException(
                        $"StartDocPrinter failed — Code: {Marshal.GetLastWin32Error()}");
                StartPagePrinter(h);
                nint ptr = Marshal.AllocCoTaskMem(data.Length);
                try
                {
                    Marshal.Copy(data, 0, ptr, data.Length);
                    if (!WritePrinter(h, ptr, data.Length, out int written) || written != data.Length)
                        throw new InvalidOperationException(
                            $"WritePrinter: wrote {written} of {data.Length} bytes");
                }
                finally { Marshal.FreeCoTaskMem(ptr); }
                EndPagePrinter(h);
                EndDocPrinter(h);
            }
            finally { ClosePrinter(h); }
        }

