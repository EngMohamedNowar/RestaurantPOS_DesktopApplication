        static string Tr(string? text)
        {
            if (string.IsNullOrWhiteSpace(text)) return text ?? "";
            if (Translations.TryGetValue(text.Trim(), out string? direct)) return direct;
            string result = text;
            foreach (var (ar, en) in Translations.OrderByDescending(x => x.Key.Length))
                result = result.Replace(ar, en, StringComparison.OrdinalIgnoreCase);
            return result;
        }

        static string SafeAscii(string s)
        {
            if (string.IsNullOrEmpty(s)) return s;
            var sb = new StringBuilder(s.Length);
            foreach (char c in s)
                if (c < 128) sb.Append(c);
            return sb.ToString().TrimEnd();
        }

