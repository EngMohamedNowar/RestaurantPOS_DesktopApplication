        static BitmapSource? GetLogoBitmapSource()
        {
            try
            {
                if (LOGO_BITMAP.Length < 8) return null;

                int xL = LOGO_BITMAP[4], xH = LOGO_BITMAP[5];
                int yL = LOGO_BITMAP[6], yH = LOGO_BITMAP[7];
                int widthBytes = xL + (xH << 8);
                int height = yL + (yH << 8);
                int width = widthBytes * 8;

                int expected = widthBytes * height;
                if (width <= 0 || height <= 0 || LOGO_BITMAP.Length - 8 < expected)
                    return null;

                byte[] pixelData = new byte[expected];
                Array.Copy(LOGO_BITMAP, 8, pixelData, 0, expected);
                for (int i = 0; i < pixelData.Length; i++)
                    pixelData[i] = (byte)~pixelData[i];

                return BitmapSource.Create(width, height, 96, 96,
                    PixelFormats.BlackWhite, null, pixelData, widthBytes);
            }
            catch { return null; }
        }

